using myFlightPerformance.Models;
using Microsoft.EntityFrameworkCore;
using System.Globalization;
using System.Text;

namespace myFlightPerformance.Services
{
    public class SegInputService : ISegInputService
    {
        private readonly ApplicationDbContext _context;


        // GET Request Services
        public SegInputService(ApplicationDbContext context)
        {
            _context = context;
        }
        
        public async Task<List<EventTrigger>> GetMalfunction()
        {
            return await _context.EventTriggers
                .Where(o => o.TrigType == EventTrigger.TrigTypeEnum.Malfunction)
                .ToListAsync();
        }

        public async Task<List<EventTrigger>> GetProcedures()
        {
                return await _context.EventTriggers
                .Where(o => o.TrigType == EventTrigger.TrigTypeEnum.Procedure)
                .ToListAsync();
        }
        public async Task<List<EventTrigger>> GetOthers()
        {
                return await _context.EventTriggers
                .Where(o => o.TrigType == EventTrigger.TrigTypeEnum.Other)
                .ToListAsync();
        }

        public async Task<List<Observation>> GetObservations()
        {
            return await _context.Observations.ToListAsync();
        }


        public async Task<int> CreateSegDocumentAsync(SegDocument segDocumentInput, List<SegDocumentJunction> segDocumentJunctionsInput)
        {
            if (segDocumentInput == null)
                throw new ArgumentNullException(nameof(segDocumentInput));

            // Ensure primary key is auto-generated by EF Core
            segDocumentInput.CreationDate = segDocumentInput.CreationDate.ToUniversalTime();


            _context.SegDocuments.Add(segDocumentInput);
            await _context.SaveChangesAsync(); // Save to get the auto-generated SegId

            if (segDocumentJunctionsInput != null && segDocumentJunctionsInput.Count > 0)
            {
                foreach (var junction in segDocumentJunctionsInput)
                {
                    junction.SegId = segDocumentInput.SegId; // Associate junction with document
                    _context.SegDocumentJunctions.Add(junction);
                }
                await _context.SaveChangesAsync();
            }

            return segDocumentInput.SegId;
        }
       


        
        

        
    }
}
